// BACKGROUND POLLER — pulls data from ESP32-S3 every 5s
// ============================================================

async fn background_poller(state: AppState) {
    println!("📊 Background Poller started (5s cycle)");
    println!("   Polling ESP32-S3 for PZEM data via ESP-NOW relay...");

    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_millis(2500))
        .build()
        .unwrap();

    loop {
        tokio::time::sleep(std::time::Duration::from_secs(5)).await;

        let s3_ip = state.esp_s3_ip.lock().await.clone();
        let wroom_ip = state.esp_wroom_ip.lock().await.clone();

        let now_ts = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        // Try ESP32-S3 /api/status first, then /data, then WROOM /data
        let urls = vec![
            format!("http://{}/api/status", s3_ip.trim()),
            format!("http://{}/data", s3_ip.trim()),
            format!("http://{}/data", wroom_ip.trim()),
        ];

        let mut got_data = false;

        for url in &urls {
            if let Ok(resp) = client.get(url).send().await {
                if let Ok(json) = resp.json::<serde_json::Value>().await {
                    let voltage = parse_num(&json, "voltage");
                    let current = parse_num(&json, "current");
                    let power = parse_num(&json, "power");
                    let energy = parse_num(&json, "energy");
                    let frequency = parse_num_or(&json, "frequency", 50.0);
                    let pf = parse_num_or(&json, "pf", 1.0);

                    // Update latest reading
                    {
                        let mut reading = state.latest_reading.lock().await;
                        reading.is_online = true;
                        reading.voltage = voltage;
                        reading.current = current;
                        reading.power = power;
                        reading.energy = energy;
                        reading.frequency = frequency;
                        reading.pf = pf;
                        reading.last_update_ts = now_ts;
                    }

                    // Push to telemetry history (rolling 60)
                    {
                        let mut history = state.telemetry_history.lock().await;
                        history.push(TelemetrySample {
                            voltage, current, power, energy, frequency, pf,
                            timestamp: now_ts,
                        });
                        if history.len() > 60 { history.remove(0); }
                    }

                    // Run alert engine
                    run_alert_engine(&state, voltage, current, power, pf, now_ts).await;

                    println!("✅ [{:.0}V {:.2}A {:.0}W] from {}", voltage, current, power, url);
                    got_data = true;
                    break; // Got data, stop trying other URLs
                }
            }
        }

        if !got_data {
            // Mark offline
            let mut reading = state.latest_reading.lock().await;
            reading.is_online = false;
            println!("❌ No data from S3({}) or WROOM({})", s3_ip, wroom_ip);
        }
    }
}

/// Parse a JSON value that could be a string or number
fn parse_num(json: &serde_json::Value, key: &str) -> f64 {
    json.get(key)
        .map(|v| {
            if let Some(n) = v.as_f64() { n }
            else if let Some(s) = v.as_str() { s.parse::<f64>().unwrap_or(0.0) }
            else { 0.0 }
        })
        .unwrap_or(0.0)
}

fn parse_num_or(json: &serde_json::Value, key: &str, default: f64) -> f64 {
    let v = parse_num(json, key);
    if v == 0.0 { default } else { v }
}

