/// GET /api/weather — Hà Nội weather with energy tips
async fn handle_weather(State(state): State<AppState>) -> impl IntoResponse {
    // Check cache (15 min TTL)
    let should_fetch = {
        let last = state.weather_last_fetch.lock().await;
        match *last {
            Some(t) => t.elapsed().as_secs() > 900,
            None => true,
        }
    };

    if should_fetch {
        if let Ok(client) = reqwest::Client::builder()
            .timeout(std::time::Duration::from_secs(5)).build()
        {
            let url = "https://api.openweathermap.org/data/2.5/weather?q=Hanoi&appid=demo&units=metric&lang=vi";
            if let Ok(resp) = client.get(url).send().await {
                if let Ok(json) = resp.json::<serde_json::Value>().await {
                    let temp = json["main"]["temp"].as_f64().unwrap_or(32.0);
                    let feels = json["main"]["feels_like"].as_f64().unwrap_or(35.0);
                    let humidity = json["main"]["humidity"].as_u64().unwrap_or(70) as u32;
                    let desc = json["weather"][0]["description"].as_str().unwrap_or("trời nắng").to_string();
                    let icon = json["weather"][0]["icon"].as_str().unwrap_or("01d").to_string();
                    let wind = json["wind"]["speed"].as_f64().unwrap_or(3.0);

                    let suggestion = if temp > 35.0 {
                        "Trời nóng! Máy lạnh tiêu thụ nhiều điện. Đặt 26°C để tiết kiệm.".into()
                    } else if temp > 30.0 {
                        "Thời tiết ấm áp. Dùng quạt thay máy lạnh để tiết kiệm điện.".into()
                    } else if desc.contains("mưa") {
                        "Trời mưa, độ ẩm cao. Hạn chế dùng máy sấy quần áo.".into()
                    } else {
                        "Thời tiết dễ chịu. Mở cửa sổ thay vì dùng máy lạnh!".into()
                    };

                    let weather = WeatherData {
                        city: "Hà Nội".into(), temp, feels_like: feels, humidity,
                        description: desc, icon, wind_speed: wind, suggestion,
                    };
                    *state.weather_cache.lock().await = Some(weather);
                    *state.weather_last_fetch.lock().await = Some(Instant::now());
                }
            }
        }
    }

    let cache = state.weather_cache.lock().await.clone();
    let weather = cache.unwrap_or(WeatherData {
        city: "Hà Nội".into(), temp: 32.0, feels_like: 35.0, humidity: 70,
        description: "trời nắng".into(), icon: "01d".into(), wind_speed: 3.5,
        suggestion: "Thời tiết ấm áp. Dùng quạt thay máy lạnh để tiết kiệm điện.".into(),
    });

    Json(weather)
}

/// POST /api/config — set ESP32 IPs from app Settings
async fn handle_config(
    State(state): State<AppState>,
    Json(payload): Json<ConfigPayload>,
) -> impl IntoResponse {
    if let Some(ip) = payload.esp_s3_ip {
        if !ip.trim().is_empty() {
            *state.esp_s3_ip.lock().await = ip.clone();
            println!("📌 ESP32-S3 IP updated to: {}", ip);
        }
    }
    if let Some(ip) = payload.esp_wroom_ip {
        if !ip.trim().is_empty() {
            *state.esp_wroom_ip.lock().await = ip.clone();
            println!("📌 WROOM IP updated to: {}", ip);
        }
    }
    Json(serde_json::json!({"status": "ok"}))
}

/// GET /api/config — return current ESP IPs (for OTA target selection)
async fn handle_get_config(State(state): State<AppState>) -> impl IntoResponse {
    let s3 = state.esp_s3_ip.lock().await.clone();
    let wroom = state.esp_wroom_ip.lock().await.clone();
    Json(serde_json::json!({
        "esp_s3_ip": s3,
        "esp_wroom_ip": wroom,
    }))
}

