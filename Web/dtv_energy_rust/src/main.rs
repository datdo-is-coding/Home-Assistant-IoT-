// SMART ALERT ENGINE
// ============================================================

async fn run_alert_engine(state: &AppState, voltage: f64, _current: f64, power: f64, pf: f64, now_ts: u64) {
    let mut new_alerts: Vec<SmartAlert> = Vec::new();

    // 1. Voltage anomaly
    if voltage > 10.0 && voltage < 200.0 {
        new_alerts.push(SmartAlert {
            level: "critical".into(), icon: "⚠️".into(),
            title: "Điện áp thấp bất thường!".into(),
            message: format!("Điện áp hiện tại {:.1}V < 200V. Kiểm tra nguồn điện!", voltage),
            timestamp: now_ts,
        });
    } else if voltage > 240.0 {
        new_alerts.push(SmartAlert {
            level: "critical".into(), icon: "⚡".into(),
            title: "Điện áp cao bất thường!".into(),
            message: format!("Điện áp {:.1}V > 240V. Tắt thiết bị nhạy cảm!", voltage),
            timestamp: now_ts,
        });
    }

    // 2. High power
    if power > 2000.0 {
        new_alerts.push(SmartAlert {
            level: "warning".into(), icon: "🔥".into(),
            title: "Công suất tiêu thụ cao!".into(),
            message: format!("Đang tiêu thụ {:.0}W. Kiểm tra máy lạnh, bếp điện.", power),
            timestamp: now_ts,
        });
    }

    // 3. Low power factor
    if pf < 0.8 && pf > 0.0 {
        new_alerts.push(SmartAlert {
            level: "warning".into(), icon: "📉".into(),
            title: "Hệ số công suất thấp".into(),
            message: format!("PF = {:.2}. Động cơ/quạt gây hao phí.", pf),
            timestamp: now_ts,
        });
    }

    // 4. Trend analysis
    {
        let history = state.telemetry_history.lock().await;
        if history.len() >= 10 {
            let recent = &history[history.len()-10..];
            let first_avg: f64 = recent[..5].iter().map(|s| s.power).sum::<f64>() / 5.0;
            let last_avg: f64 = recent[5..].iter().map(|s| s.power).sum::<f64>() / 5.0;
            if last_avg > first_avg * 1.3 && last_avg > 100.0 {
                new_alerts.push(SmartAlert {
                    level: "info".into(), icon: "📈".into(),
                    title: "Xu hướng tăng tiêu thụ".into(),
                    message: format!("Công suất tăng từ {:.0}W → {:.0}W trong 50s qua.", first_avg, last_avg),
                    timestamp: now_ts,
                });
            }
        }
    }

    // 5. Energy saving tip
    if power < 500.0 && power > 0.0 {
        new_alerts.push(SmartAlert {
            level: "tip".into(), icon: "💡".into(),
            title: "Gợi ý tiết kiệm điện".into(),
            message: "Tiêu thụ ổn định. Tắt đèn và thiết bị không dùng để tiết kiệm thêm!".into(),
            timestamp: now_ts,
        });
    }

    *state.alerts.lock().await = new_alerts;
}

