#[derive(Deserialize)]
struct GoogleAssistantRequest {
    intent: Option<String>,
}

#[derive(Serialize)]
struct GoogleAssistantResponse {
    speech_response: String,
    status: String,
    voltage: f64,
    power: f64,
    energy: f64,
}

/// POST /api/google-assistant — Webhook for Google Assistant Actions & Voice Intent Query
async fn handle_google_assistant(
    State(state): State<AppState>,
    Json(payload): Json<GoogleAssistantRequest>,
) -> impl IntoResponse {
    let reading = state.latest_reading.lock().await.clone();
    let intent = payload.intent.unwrap_or_else(|| "query_status".to_string());

    let speech = match intent.as_str() {
        "query_voltage" => format!("Điện áp mạng điện nhà bạn hiện tại là {:.1} Volts.", reading.voltage),
        "query_power" => format!("Công suất tiêu thụ điện năng tức thời hiện tại là {:.0} Watts.", reading.power),
        "query_energy" => format!("Tổng điện năng tích lũy đã tiêu thụ là {:.2} Kilo-Watt giờ.", reading.energy),
        "query_pf" => format!("Hệ số công suất Power Factor hiện tại là {:.2}.", reading.pf),
        _ => if reading.is_online {
            format!("Hệ thống điện DTV Energy hoạt động bình thường. Điện áp: {:.1} Volts, Công suất: {:.0} Watts.", reading.voltage, reading.power)
        } else {
            "Cảnh báo: Hiện chưa nhận được dữ liệu từ cảm biến đo điện năng ESP32.".to_string()
        },
    };

    Json(GoogleAssistantResponse {
        speech_response: speech,
        status: "SUCCESS".to_string(),
        voltage: reading.voltage,
        power: reading.power,
        energy: reading.energy,
    })
}

