#[tokio::main]
async fn main() {
    println!("🦀 DTV Energy Smart Hub — Rust Core Server");
    println!("   Architecture: App ──> Rust Server ──> ESP32-S3 ──> WROOM");
    println!();

    let state = AppState {
        esp_s3_ip: Arc::new(Mutex::new("192.168.11.181".to_string())),
        esp_wroom_ip: Arc::new(Mutex::new("192.168.11.182".to_string())),
        latest_reading: Arc::new(Mutex::new(LiveReading::default())),
        alerts: Arc::new(Mutex::new(Vec::new())),
        weather_cache: Arc::new(Mutex::new(None)),
        weather_last_fetch: Arc::new(Mutex::new(None)),
        telemetry_history: Arc::new(Mutex::new(Vec::new())),
    };

    // Spawn background poller (ESP32-S3 → Rust every 5s)
    let bg = state.clone();
    tokio::spawn(async move { background_poller(bg).await; });

    let app = Router::new()
        .route("/", get(serve_ui))
        // === UNIFIED API — Flutter, Web UI, Google Assistant & Android App OTA ===
        .route("/api/status", get(handle_status))       // Live metrics (cached)
        .route("/api/data", get(handle_status))         // Legacy UI alias
        .route("/api/alerts", get(handle_alerts))        // Smart alerts
        .route("/api/weather", get(handle_weather))      // Weather Hà Nội
        .route("/api/analytics", get(handle_analytics))  // Chart history
        .route("/api/config", post(handle_config))       // Set ESP IPs
        .route("/api/config", get(handle_get_config))    // Get ESP IPs (for OTA)
        .route("/api/google-assistant", post(handle_google_assistant)) // Google Assistant webhook
        .route("/api/app-version", get(handle_app_version)) // Android App OTA version check
        .route("/downloads/app-debug.apk", get(serve_apk))   // Android App APK download
        .layer(CorsLayer::permissive())
        .with_state(state);

    let addr = SocketAddr::from(([0, 0, 0, 0], 8080));
    println!("🚀 Server running at http://0.0.0.0:8080");
    println!("   GET  /api/status    → Live voltage/current/power/energy");
    println!("   GET  /api/alerts    → Smart alerts & tips");
    println!("   GET  /api/weather   → Hà Nội weather");
    println!("   GET  /api/analytics → 60-sample chart history");
    println!("   POST /api/config    → Set ESP32 IPs");
    println!("   GET  /api/config    → Get ESP32 IPs (for OTA targets)");
    println!();

    let listener = tokio::net::TcpListener::bind(addr).await.unwrap();
    axum::serve(listener, app).await.unwrap();
}

