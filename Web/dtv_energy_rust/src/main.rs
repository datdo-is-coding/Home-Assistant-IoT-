#[derive(Clone)]
struct AppState {
    /// IP of ESP32-S3 Master (hub connects to this to pull data)
    esp_s3_ip: Arc<Mutex<String>>,
    /// IP of ESP32 WROOM Slave (for direct fallback or OTA proxy)
    esp_wroom_ip: Arc<Mutex<String>>,
    /// Latest live reading from ESP32-S3 (cached by background poller)
    latest_reading: Arc<Mutex<LiveReading>>,
    /// Smart alerts generated by analysis engine
    alerts: Arc<Mutex<Vec<SmartAlert>>>,
    /// Weather cache
    weather_cache: Arc<Mutex<Option<WeatherData>>>,
    weather_last_fetch: Arc<Mutex<Option<Instant>>>,
    /// Rolling telemetry history (max 60 samples for charts)
    telemetry_history: Arc<Mutex<Vec<TelemetrySample>>>,
}

/// The single unified data structure Flutter receives from /api/status
#[derive(Serialize, Deserialize, Clone, Debug)]
struct LiveReading {
    is_online: bool,
    voltage: f64,
    current: f64,
    power: f64,
    energy: f64,
    frequency: f64,
    pf: f64,
    last_update_ts: u64,
}

impl Default for LiveReading {
    fn default() -> Self {
        Self {
            is_online: false,
            voltage: 0.0, current: 0.0, power: 0.0, energy: 0.0,
            frequency: 50.0, pf: 1.0, last_update_ts: 0,
        }
    }
}

#[derive(Serialize, Clone, Debug)]
struct SmartAlert {
    level: String,
    icon: String,
    title: String,
    message: String,
    timestamp: u64,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
struct WeatherData {
    city: String,
    temp: f64,
    feels_like: f64,
    humidity: u32,
    description: String,
    icon: String,
    wind_speed: f64,
    suggestion: String,
}

#[derive(Serialize, Clone, Debug)]
struct TelemetrySample {
    voltage: f64,
    current: f64,
    power: f64,
    energy: f64,
    frequency: f64,
    pf: f64,
    timestamp: u64,
}

#[derive(Deserialize)]
struct ConfigPayload {
    esp_s3_ip: Option<String>,
    esp_wroom_ip: Option<String>,
}

